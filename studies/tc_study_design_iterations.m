function R = tc_study_design_iterations()
% TC_STUDY_DESIGN_ITERATIONS  Not a simulation.  Reads docs/DECISIONS.md and outputs/ablations.txt and writes
%   docs/DESIGN_ITERATIONS.md: the controller and estimator decisions as a sequence
%   specification -> choice -> check -> revision, including the rejected ones.
%   Every decision listed here is looked up in DECISIONS.md by its D-number and title; every number quoted in the
%   narrative is looked up (as the literal string) in DECISIONS.md or ablations.txt, and the run fails if one is
%   missing.  Ablation rows are parsed from ablations.txt, not typed.  Writes outputs/tc_study_design_iterations.txt.
  here = fileparts(mfilename('fullpath'));  root = fileparts(here);  addpath(root);  tc_setup();
  Dtxt = fileread(fullfile(root, 'docs', 'DECISIONS.md'));  Atxt = fileread(fullfile(root, 'outputs', 'ablations.txt'));
  [say, done] = tc_course_report('tc_study_design_iterations');
  both = [Dtxt "\n" Atxt];

  % ---- decisions present in DECISIONS.md --------------------------------------------------------------------
  tk = regexp(Dtxt, '(?m)^## (D\d+)[ ]+([^\n]*)', 'tokens');
  ids = cellfun(@(c) c{1}, tk, 'UniformOutput', false);  ttl = cellfun(@(c) c{2}, tk, 'UniformOutput', false);
  say('DECISIONS.md contains %d decisions: %s\n\n', numel(ids), strjoin(ids, ' '));

  % ---- ablation rows -------------------------------------------------------------------------------------------
  ab = struct();  lines = strsplit(Atxt, "\n");
  for k = 1:numel(lines)
    m = regexp(lines{k}, '^(\w+)\s+(\d+)/(\d+)\s+(\d+) \|\s+([+-][\d.]+) \[\s*([+-][\d.]+),\s*([+-][\d.]+)\]\s+([\d.]+) \|\s+([+-][\d.]+) \[\s*([+-][\d.]+),\s*([+-][\d.]+)\]\s+([\d.]+)', 'tokens', 'once');
    if ~isempty(m), ab.(m{1}) = m; end
  end
  vnames = fieldnames(ab);
  say('ablations.txt rows parsed: %s\n\n', strjoin(vnames', ' '));
  fa = @(v) sprintf('%s: %s/%s intercepted, %s pulse miss(es), d t_first %s s [%s, %s] (p_Holm %s), d RMS %s m [%s, %s] (p_Holm %s)', v, ab.(v){2}, ab.(v){3}, ab.(v){4}, ab.(v){5}, ab.(v){6}, ab.(v){7}, ab.(v){8}, ab.(v){9}, ab.(v){10}, ab.(v){11}, ab.(v){12});

  E = {};   % id, track, title, spec, choice, check, revision, status, evidence strings, ablation variants
  E(end+1,:) = {'D8', 'controller', 'Feedback gains and generator pole', ...
    'An LTI compensator for G_p with analytic stability support (handout Sec. 4); no re-tuning per scenario.', ...
    'K_p = 4000 V/rad, T_i = 1 s, tau_f = 0.03 s and p = 20 rad/s taken from the reference repository and NOT re-optimised.', ...
    'Re-derived what they imply: crossover 4.10 rad/s, PM 68.5 deg, GM 16.1 dB, M_s 1.21, Routh limit for proportional-only 10 484 V/rad, full loop stable to 6.35x the design gain, type 2 with K_a = 3.99 1/s^2; the FVT parabola error confirmed by partial fractions (0.0150 rad both ways).', ...
    'No revision of the numbers.  The final-design ablations of the generator pole (below) show both neighbours slower in first hit, which is a check on p = 20, not a re-optimisation.', ...
    'kept', {'crossover 4.10 rad/s', 'PM 68.5 deg', 'GM 16.1 dB', '10 484 V/rad', '6.35x', '0.0150 rad'}, {'p_dev_10', 'p_dev_30'}};
  E(end+1,:) = {'D5', 'controller', 'Acquisition anti-windup (freeze_acq)', ...
    'In scenario A the clamp-limited slew overshot by ~3 m and P_hit crossed 0.99 only at t ~ 1.3 s, because the PI integrator had accumulated lag while the reference was not following the linear law.', ...
    'Pause the PI integrator while the cascade clamps are active (freeze_acq).', ...
    'On exploration seeds MC201-240 mean first hit 1.621 -> 1.545 s (40/40, 0 misses).', ...
    'REVISED: the gain was confounded by the slip guard (D12).  In the final design the ablation no_freeze is -0.005 s [-0.022, +0.012], Holm p = 1.0: no effect.  The flag stays on as the conservative choice; the benefit is not claimed.', ...
    'kept, benefit withdrawn', {'1.621 -> 1.545 s', '-0.005 s [-0.022, +0.012]', 'Holm p = 1.0'}, {'no_freeze'}};
  E(end+1,:) = {'D6', 'controller', 'Acceleration clamp from a current budget', ...
    'The handout states no current limit; acquisition needs an acceleration bound that a motor could deliver.', ...
    'acq_accel = 0.8 N K_t i_lim / J_eq with an ASSUMED i_lim = 10 A, i.e. 2.5 rad/s^2.', ...
    'Relaxing to 5 rad/s^2 (about 16 A) cut mean first hit by 0.21 s with no misses on MC201-240.  Peak current is reported: 8.8 A on D6 at 100 Hz, up to 10.7-11.4 A in some robustness rows and 20 A with Kt -20 % / Ke +20 %.', ...
    'REJECTED as default: 5 rad/s^2 exceeds any current the handout can justify; the 20 % margin covers the reference acceleration only, so the budget is an acquisition guideline, not a hard current limit.  K.i_lim is the single place to change.', ...
    'rejected (larger clamp)', {'5 rad/s^2', '0.21 s', '8.8 A', '20 A'}, {}};
  E(end+1,:) = {'D7', 'controller', 'Braking-curve slew (acq_decel)', ...
    'Shave the exponential tail of the acquisition slew to hit earlier.', ...
    'Constant-deceleration braking beyond the linear zone (acq_decel).', ...
    'Exploration seeds MC201-260: decel 1.5 gave -0.127 s mean first hit but 2 pulse misses; decel 3.0 gave +0.072 s.  Because that was a selection on the same seeds it was confirmed once on fresh seeds MC2000-2099.', ...
    'REJECTED: on the fresh seeds decel 1.5 was slower, +0.093 s [+0.080, +0.104], 0 vs 1 pulse misses; the exploration gain did not replicate.  Stays off (acq_decel = 0).', ...
    'rejected', {'-0.127 s', '+0.072', '+0.093 s [+0.080, +0.104]'}, {'brake_slew'}};
  E(end+1,:) = {'D11', 'controller', 'Mid-hold reference lead (lead_hold)', ...
    'The command is held for one call period; compensate by evaluating the reference half a period ahead ("ZOH compensation", my own idea).', ...
    'lead_hold: shift the reference by up to lead_max.', ...
    'Reasoning: the beam is judged at the sampling instants and the exact inverse already tracks the nowcast, so the lead moves the aim point ahead of the target by (LOS rate x lead), about 2 m at 20 Hz.  Paired MC201-260 at 20 Hz: pointing RMS 0.996 m without vs 1.677 m with (+0.717 m [+0.572, +0.863]); at 100 Hz +0.07 m; on the HB family -0.053 m without it.', ...
    'REJECTED and removed: default lead_hold = false (the option stays for the ablation table).', ...
    'rejected', {'0.996 m', '1.677 m', '+0.717 m [+0.572, +0.863]'}, {'lead_on'}};
  E(end+1,:) = {'D16', 'controller', 'Adaptive velocity feed-forward (adapt_ff)', ...
    'Robustness to plant mismatch: the velocity feed-forward term is ~ N K_e and is the sensitive one.', ...
    'adapt_ff: move integrator content into the velocity feed-forward gain.', ...
    'No change on the nominal plant; in the worst mismatch corner (Kt -20 %, Ke +20 %) RMS stays at 3.7 m with a 20 A peak; in the opposite corner it moves 1.57 -> 1.50 m.', ...
    'REJECTED as default: stays off.  A better remedy (estimating K_e from the (V, omega) residual with persistent excitation) is future work, not claimed.', ...
    'rejected', {'3.7 m', '1.57 -> 1.50 m'}, {'adapt_ff'}};
  E(end+1,:) = {'', 'controller', 'Reference aim point: present bearing vs bearing t_p ahead', ...
    'The handout asks for a prediction horizon t_p = 0.5 s in the architecture.', ...
    'Cancel the t_p advance inside the reference generator so the beam follows the nowcast (K.aim_ahead = 0).', ...
    'Ablation aim_tp (aim the beam t_p ahead, same fire rule) in outputs/ablations.txt.', ...
    'The literal reading of the prediction block is the alternative; the cancelled-advance design is kept (see the table row).', ...
    'adopted (alternative measured)', {'aim_tp'}, {'aim_tp'}};
  E(end+1,:) = {'D13', 'estimator', 'Adaptive process noise', ...
    'Maneuvers inside blackouts and bang-bang jerk (the HB family) violate a fixed process-noise assumption.', ...
    'Scale the process noise with a normalised-innovation statistic.', ...
    'On smooth MC engagements switching it off changes nothing (+0.006 s, p = 0.73).  On HB201-240 removing it costs +0.094 m pointing RMS [+0.062, +0.127].', ...
    'Kept because of the adversarial family.', ...
    'kept', {'+0.006 s, p = 0.73', '+0.094 m pointing RMS [+0.062, +0.127]'}, {'no_adapt_q'}};
  E(end+1,:) = {'D10', 'estimator', 'Calibration layer for P_hit', ...
    'The fire rule needs a calibrated hit probability.', ...
    'Isotonic map fitted on tuning seeds MC1-200.', ...
    'Scored on MC5000-5199 (37 297 ticks, base rate 0.886): Brier 0.00353 raw -> 0.00353 calibrated; the Rao-Blackwellised posterior is already close to calibrated.', ...
    'NOT ADOPTED, kept as a reported null: the identity table ships; the fitted candidate is outputs/calib_fit_candidate.m.txt.', ...
    'rejected', {'37 297 ticks', '0.00353 calibrated'}, {}};
  E(end+1,:) = {'D14', 'estimator', 'Features with a measured null effect', ...
    'Value-aware bar after the first pulse (p_sure_after), n_upd_min = 4, posterior vs the 17-class hit model.', ...
    'Keep the principled versions; the 17-class model only as the comparison baseline.', ...
    'p_sure_after and n_upd_min = 4 produced exactly zero difference on MC201-260; posterior vs 17-class differs by 9 ms.', ...
    'Kept and reported as neutral; no benefit claimed.', ...
    'neutral', {'*exactly* zero', '9 ms'}, {'classes', 'psure_flat', 'fast_fire'}};
  E(end+1,:) = {'D12', 'estimator', 'Fire slip guard (sweep_guard)', ...
    'A safeguard for an evaluator that judges between calls: block shots when the beam-vs-target slip over one call period exceeds 0.5 m (my own idea).', ...
    'sweep_guard = 0.5 m.', ...
    'Measured cost with no benefit: first-hit time 0.21 s at 100 Hz and 1.1 s at 20 Hz, pulse misses not increased when removed (MC201-260).', ...
    'REJECTED as default: sweep_guard = Inf; guard_window is kept so it is rate-independent if an evaluator ever needs it.', ...
    'rejected', {'0.21 s at 100 Hz and 1.1 s at 20 Hz'}, {'guard_on'}};
  E(end+1,:) = {'D15', 'estimator', 'The "correlated copies" failure: a harness bug, not an estimator weakness', ...
    'Robustness to evaluator conventions for meas_valid (the "drift" convention: flag 1 on every call).', ...
    'First robustness run: 14 pulse misses and a median RMS of 2.56 m.  Raising min_gap (0.4 -> 0.9 radar periods) did not help.', ...
    'That pointed away from the estimator: the harness kept meas_valid = 1 during blackouts, building the sample from a stale held measurement.', ...
    'REVISED: harness fixed; re-run MC201-230 gives 0 misses and median RMS 0.570 m at the default gap, so min_gap = 0.4 x 50 ms stays.', ...
    'revised (harness fixed)', {'14 pulse misses', '2.56 m', '0.570 m'}, {}};

  % ---- verify that everything quoted exists in the files -------------------------------------------------------
  nbad = 0;  nchk = 0;
  for q = 1:size(E,1)
    if ~isempty(E{q,1})
      j = find(strcmp(ids, E{q,1}), 1);
      if isempty(j), error('tc_study_design_iterations: %s not found in DECISIONS.md', E{q,1}); end
      say('%-4s found in DECISIONS.md: "%s"\n', E{q,1}, ttl{j});
    end
    for ev = E{q,9}
      nchk = nchk + 1;
      if isempty(strfind(both, ev{1})), nbad = nbad + 1;  say('  MISSING evidence string for %s: "%s"\n', E{q,1}, ev{1}); end
    end
    for v = E{q,10}
      if ~isfield(ab, v{1}), nbad = nbad + 1;  say('  MISSING ablation row for %s: %s\n', E{q,1}, v{1}); end
    end
  end
  say('\nEvidence strings looked up in DECISIONS.md / ablations.txt: %d checked, %d missing\n', nchk, nbad);
  not_listed = setdiff(ids, E(:,1)');
  say('Decisions in the file that are infrastructure or test-method decisions and appear only in the short list: %s\n', strjoin(not_listed, ' '));
  if nbad > 0, done(); error('tc_study_design_iterations: %d quoted items not found in the source files', nbad); end

  % ---- write the note ------------------------------------------------------------------------------------------
  fid = fopen(fullfile(root, 'docs', 'DESIGN_ITERATIONS.md'), 'w');
  fprintf(fid, '# Design iterations: specification -> choice -> check -> revision\n\n');
  fprintf(fid, 'Generated by `studies/tc_study_design_iterations.m` from `docs/DECISIONS.md` (decisions D1-D%d) and `outputs/ablations.txt` (final-design paired ablations on seeds 201-260). Nothing here is a new simulation; every decision is looked up by its D-number and every number quoted was found as a literal string in those two files when the note was written. Seed ranges follow `docs/PROTOCOL.md`.\n\n', numel(ids));
  tr = {'controller', 'Controller (feed-forward, PI loop, reference generator, acquisition)'; 'estimator', 'Estimator and fire control'};
  for t = 1:2
    fprintf(fid, '## %s\n\n', tr{t,2});
    for q = find(strcmp(E(:,2), tr{t,1}))'
      tag = E{q,1};  if isempty(tag), tag = 'ablation only'; end
      fprintf(fid, '### %s %s  (outcome: %s)\n\n', tag, E{q,3}, E{q,8});
      fprintf(fid, '- **Specification.** %s\n- **Choice.** %s\n- **Check.** %s\n- **Revision / outcome.** %s\n', E{q,4}, E{q,5}, E{q,6}, E{q,7});
      for v = E{q,10}, fprintf(fid, '- **Final-design ablation** (`outputs/ablations.txt`) %s.\n', fa(v{1})); end
      fprintf(fid, '\n');
    end
  end
  fprintf(fid, '## Verification and infrastructure decisions (short list)\n\n');
  inf = {'D1', 'cached-matrix test was NaN-blind (bug found by the first test run; fixed, regression guard added)'; ...
         'D2', 'envelope obligation is 0-10 s, not the 11 s table'; 'D3', 'test tolerances replaced by convergence-order checks'; ...
         'D4', 'harness conventions: call rates are integer multiples of 20 Hz; each radar sample delivered once'; ...
         'D9', 'MATLAB compatibility of the submission path audited by reading only, never run'; 'D17', 'controller cost measured; the 1 kHz headroom claim is only modest'};
  for q = 1:size(inf,1)
    j = find(strcmp(ids, inf{q,1}), 1);
    if isempty(j), error('%s missing from DECISIONS.md', inf{q,1}); end
    fprintf(fid, '- **%s** (%s): %s.\n', inf{q,1}, ttl{j}, inf{q,2});
  end
  fprintf(fid, '\n## Ablation table (all rows parsed from `outputs/ablations.txt`)\n\n| variant | intercepted | pulse misses | d t_first [s] | 95 %% CI | p (Holm) | d RMS [m] | 95 %% CI | p (Holm) |\n|---|---|---|---|---|---|---|---|---|\n');
  for k = 1:numel(vnames)
    a = ab.(vnames{k});
    fprintf(fid, '| `%s` | %s/%s | %s | %s | [%s, %s] | %s | %s | [%s, %s] | %s |\n', vnames{k}, a{2}, a{3}, a{4}, a{5}, a{6}, a{7}, a{8}, a{9}, a{10}, a{11}, a{12});
  end
  fprintf(fid, '\nThe sequence in one line: each idea was stated as a specification, implemented as a flag in `core/tc_params.m`, checked with a paired comparison on identical seeds, and then kept, kept as neutral, withdrawn or rejected; the rejected ones (larger clamp, braking curve, mid-hold lead, slip guard, calibration map, adaptive feed-forward) stay in the code behind a flag or in `outputs/` so the evidence can be re-read.\n');
  fclose(fid);
  say('wrote docs/DESIGN_ITERATIONS.md (%d entries + %d short-list items)\n', size(E,1), size(inf,1));
  done();
  R.ids = ids;  R.entries = E(:,1);  R.ab = ab;  R.n_evidence = nchk;
end
