function tc_calibration_study(fit_seeds, test_seeds, write_table)
% TC_CALIBRATION_STUDY  Fit the isotonic hit-probability map on TUNING seeds only and score
% it on a disjoint held-out range (vulnerabilities F.5: P_hit was previously both a
% decision variable and evaluated on the same data).
%   tc_calibration_study(1:200, 5000:5199, true)
% Data: at every tick where the filter is tracking with >= n_upd_min updates, the raw
% probability P_raw and the counterfactual outcome "a pulse fired at this instant hits".
% Brier score and a reliability table are printed before and after calibration.
  here = fileparts(mfilename('fullpath'));  addpath(fileparts(here));  tc_setup();
  if nargin < 1, fit_seeds = 1:200; end
  if nargin < 2, test_seeds = 5000:5199; end
  if nargin < 3, write_table = false; end
  assert(isempty(intersect(fit_seeds, test_seeds)), 'fit and test seeds must be disjoint');
  tc_settings('set', struct('calib_off', true));
  [pf, yf] = collect(fit_seeds);
  [kx, ky] = tc_isotonic_fit(pf, yf, 14);
  T = struct('kx', kx, 'ky', ky);
  [pt, yt] = collect(test_seeds);
  tc_settings('clear');
  pc = arrayfun(@(p) tc_calibrate_probability(T, p), pt);
  fprintf('held-out ticks: %d   base rate %.3f\n', numel(yt), mean(yt));
  fprintf('Brier raw        : %.5f\n', mean((pt - yt).^2));
  fprintf('Brier calibrated : %.5f\n', mean((pc - yt).^2));
  edges = [0 0.5 0.8 0.9 0.95 0.99 0.999 1.0001];
  fprintf('%-14s %7s %9s %9s %9s\n', 'raw bin', 'n', 'mean raw', 'observed', 'calibr.');
  for b = 1:numel(edges)-1
    w = pt >= edges(b) & pt < edges(b+1);
    if any(w), fprintf('[%.3f,%.3f) %7d %9.4f %9.4f %9.4f\n', edges(b), edges(b+1), sum(w), mean(pt(w)), mean(yt(w)), mean(pc(w))); end
  end
  if write_table
    out = fullfile(fileparts(here), 'core', 'tc_calibration_table.m');
    fid = fopen(out, 'w');
    fprintf(fid, 'function T = tc_calibration_table()\n%% TC_CALIBRATION_TABLE  Isotonic map raw -> calibrated hit probability.\n');
    fprintf(fid, '%% GENERATED by studies/tc_calibration_study.m from tuning seeds %d..%d only.\n', fit_seeds(1), fit_seeds(end));
    fprintf(fid, '%% Held-out Brier: raw %.5f -> calibrated %.5f (seeds %d..%d).  Do not edit by hand.\n', mean((pt - yt).^2), mean((pc - yt).^2), test_seeds(1), test_seeds(end));
    fprintf(fid, '  T.kx = [%s];\n  T.ky = [%s];\nend\n', sprintf('%.6g ', kx), sprintf('%.6g ', ky));
    fclose(fid);  fprintf('wrote %s\n', out);
  end
end

function [p, y] = collect(seeds)
  p = [];  y = [];
  for s = seeds
    o = tc_run_engagement(sprintf('MC%d', s), struct('f_ctrl', 100));
    L = o.log;  w = L.ready & isfinite(L.p_raw);
    idx = find(w);  idx = idx(1:5:end);                  % thin (neighbouring ticks are nearly identical)
    p = [p; L.p_raw(idx)'];  y = [y; L.hit_now(idx)'];
  end
end
